"""Data models for AuditPilot.

Defines Pydantic schemas for crawled pages, deterministic findings,
category score breakdowns, critical issue caps, and structured LLM outputs.
"""

from typing import Any, Literal

from pydantic import BaseModel, Field


class PageData(BaseModel):
    """Raw and parsed data extracted from a single crawled URL."""

    url: str
    status_code: int
    final_url: str
    redirect_chain: list[str] = Field(default_factory=list)
    response_time_ms: float = 0.0
    html_size_bytes: int = 0
    title: str | None = None
    meta_description: str | None = None
    h1s: list[str] = Field(default_factory=list)
    headings: list[tuple[int, str]] = Field(default_factory=list)
    word_count: int = 0
    images_total: int = 0
    images_missing_alt: int = 0
    internal_links: list[str] = Field(default_factory=list)
    external_links: list[str] = Field(default_factory=list)
    canonical: str | None = None
    meta_robots: str | None = None
    json_ld_types: list[str] = Field(default_factory=list)
    top_terms: list[str] = Field(default_factory=list)
    raw_html: str | None = None
    headers: dict[str, str] = Field(default_factory=dict)
    semantic_landmarks: list[str] = Field(default_factory=list)
    has_placeholder_content: bool = False
    form_inputs_without_labels: int = 0
    open_graph_tags: list[str] = Field(default_factory=list)
    html_lang: str | None = None
    viewport_content: str | None = None
    images_missing_dimensions: int = 0
    images_modern_or_lazy: int = 0
    render_blocking_scripts: int = 0
    forms_count: int = 0
    form_inputs_total: int = 0
    form_inputs_validated: int = 0
    dead_links: int = 0
    anchors_total: int = 0
    unsafe_blank_links: int = 0
    positive_tabindex_count: int = 0
    cta_count: int = 0
    has_contact_signal: bool = False
    mixed_content_urls: list[str] = Field(default_factory=list)
    clean_text: str = Field(default="", exclude=True)


class SiteSignals(BaseModel):
    """Site-level evidence gathered once per crawl. None means the probe was not run."""

    robots_found: bool | None = None
    robots_valid: bool | None = None
    robots_blocks_all: bool | None = None
    robots_directive_count: int = 0
    sitemap_found: bool | None = None
    sitemap_valid: bool | None = None
    sitemap_url: str | None = None
    sitemap_url_count: int = 0
    http_redirects_to_https: bool | None = None
    urls_blocked_by_robots: list[str] = Field(default_factory=list)


class Finding(BaseModel):
    """Result of an evidence-backed deterministic check."""

    check_id: str
    category: Literal[
        "availability",
        "seo",
        "performance",
        "ui_ux",
        "content",
        "functionality",
        "security",
        "accessibility",
        "onpage",  # backwards compatible mapping
        "technical",  # backwards compatible mapping
    ]
    status: Literal["pass", "partial", "fail", "not_applicable", "not_tested", "error"] = "pass"
    points_earned: float = 0.0
    max_points: float = 0.0
    severity: Literal["critical", "high", "medium", "low", "warning", "info"] = "info"
    impact: Literal["high", "medium", "low"] = "medium"
    passed: bool = True
    message: str
    affected_urls: list[str] = Field(default_factory=list)
    evidence: dict[str, Any] = Field(default_factory=dict)
    recommendation: str = ""


class ActionItem(BaseModel):
    """A prioritized, actionable fix generated by the LLM analysis layer."""

    rank: int
    title: str
    why_it_matters: str
    how_to_fix: str
    affected_urls: list[str] = Field(default_factory=list)
    impact: Literal["high", "medium", "low"]
    effort: Literal["high", "medium", "low"]


class LLMReport(BaseModel):
    """Structured report produced by the LLM analysis layer."""

    executive_summary: str
    action_plan: list[ActionItem]
    quick_wins: list[str]
    content_insights: list[str]
    competitor_notes: list[str] | None = None


class CategoryScore(BaseModel):
    """Score summary for an individual audit category."""

    id: str = ""
    name: str
    weight: float = 0.0
    earned_points: float = 0.0
    max_points: float = 0.0
    score: float  # Percentage 0 to 100
    coverage_percent: float = 100.0
    grade: str = "A"
    status: str = "assessed"
    critical_count: int = 0
    warning_count: int = 0
    info_count: int = 0


class AuditScore(BaseModel):
    """Overall and category scoring breakdown with caps and confidence."""

    raw_score: float = 0.0
    final_score: float = 0.0
    overall: float = 0.0  # Alias for final_score
    grade: str = "A"
    maximum_cap: float | None = None
    rating: str = "Good"  # Excellent, Very Good, Good, Average, Needs Improvement, Poor, Critical, Not assessable
    confidence: str = "high"  # high, medium, low, not_assessable
    coverage_percent: float = 100.0
    score_caps_applied: list[str] = Field(default_factory=list)
    not_tested_checks: list[str] = Field(default_factory=list)
    categories: dict[str, CategoryScore] = Field(default_factory=dict)


class AuditResult(BaseModel):
    """Complete container for an end-to-end audit run."""

    target_url: str
    domain: str
    pages_crawled: int
    pages: list[PageData]
    findings: list[Finding]
    score: AuditScore
    llm_report: LLMReport | None = None
